import { activeLessons } from "./store.js";
import type { LessonStore } from "./schemas.js";

/**
 * Render a *proposed* skill update from accumulated lessons.
 *
 * This deliberately does not write to `.agents/skills/**`. Rewriting
 * skill documentation from review answers without a human reading the
 * diff is how a bad afternoon turns into a permanent wrong rule that
 * every future project inherits. The proposal is a file a human opens,
 * edits, and accepts.
 */
export function skillUpdateProposal(store: LessonStore): string {
  const active = activeLessons(store, "skill");
  const imageRules = activeLessons(store, "image-prompt");
  const draftRules = activeLessons(store, "draft");
  const renderRules = activeLessons(store, "render");

  const out: string[] = [
    "# Skill update proposal (from human review)",
    "",
    "Generated by `video learn --propose`. **Not applied.** Review this",
    "file, edit what you agree with, then fold the survivors into the",
    "relevant `.agents/skills/*/SKILL.md` by hand.",
    "",
  ];

  const sections: [string, typeof active][] = [
    ["Image-prompt rules (already active — these steer prompts automatically)", imageRules],
    ["Draft / article rules", draftRules],
    ["Render / output rules", renderRules],
    ["Skill-process rules", active],
  ];

  let any = false;
  for (const [title, lessons] of sections) {
    out.push(`## ${title}`, "");
    if (lessons.length === 0) {
      out.push("_none yet_", "");
      continue;
    }
    any = true;
    for (const lesson of lessons) {
      const seen =
        lesson.seenCount > 1
          ? ` — raised ${lesson.seenCount}× (${lesson.projects.join(", ")})`
          : ` — high confidence (${lesson.projects.join(", ")})`;
      out.push(`- ${lesson.statement}${seen}`);
    }
    out.push("");
  }

  if (!any) {
    out.push(
      "_No active lessons yet. Record a review with `video learn <project>`_",
      "_first._",
      "",
    );
  }
  return out.join("\n");
}