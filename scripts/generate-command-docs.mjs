// Regenerates every doc section that mirrors cli/src/minimal-api.ts and
// video-components/src/theme.ts, plus the schema.md theme example line.
// Run via `pnpm run docs:commands` (builds first — this reads package dist/).
// Markers: <!-- BEGIN: <id> (generated ...) --> / <!-- END: <id> -->.
// Exits non-zero if a marker is missing so CI catches renames.
import { readFileSync, writeFileSync } from "node:fs";
import { format as prettierFormat } from "prettier";

const { MINIMAL_API_COMMANDS } =
  await import("../packages/cli/dist/minimal-api.js");
const { THEMES, THEME_META, THEME_NAMES, DEFAULT_THEME_NAME } =
  await import("../packages/video-components/dist/theme.js");

const files = {
  readme: "README.md",
  install: "docs/INSTALLATION_AND_USAGE.md",
  schema: "docs/schema.md",
};

function replaceSection(content, id, body) {
  const begin = new RegExp(
    `<!--\\s*BEGIN: ${id}[^>]*-->\\n[\\s\\S]*?<!--\\s*END: ${id}\\s*-->`,
  );
  const replacement = `<!-- BEGIN: ${id} (generated by \`pnpm run docs:commands\` — do not edit) -->\n${body}\n<!-- END: ${id} -->`;
  if (!begin.test(content)) {
    throw new Error(
      `marker "${id}" not found — was it renamed or hand-deleted?`,
    );
  }
  return content.replace(begin, replacement);
}

function themeOrder() {
  return [
    DEFAULT_THEME_NAME,
    ...THEME_NAMES.filter((n) => n !== DEFAULT_THEME_NAME),
  ];
}

function readmeCommandTable() {
  const rows = MINIMAL_API_COMMANDS.map(
    (c) => `| \`${c.invocation}\` | ${c.purpose} |`,
  );
  return ["| Command | Purpose |", "| --- | --- |", ...rows].join("\n");
}

function readmeThemeTable() {
  const rows = themeOrder().map((name) => {
    const meta = THEME_META[name];
    const label =
      name === DEFAULT_THEME_NAME ? `\`${name}\` (default)` : `\`${name}\``;
    const mood = `${meta.bg} / ${meta.mood}`;
    const accent = THEMES[name].colors.accent;
    return `| ${label} | ${mood} | \`${accent}\` |`;
  });
  return ["| Name | Mood | Accent |", "| --- | --- | --- |", ...rows].join(
    "\n",
  );
}

function installThemeTable() {
  const rows = themeOrder().map((name) => {
    const meta = THEME_META[name];
    const mood =
      name === DEFAULT_THEME_NAME
        ? `${meta.note} — ${meta.bestFor}`
        : meta.bestFor;
    return `| \`${name}\` | ${meta.bg} | ${meta.accent} | ${mood} |`;
  });
  return [
    "| `style.theme` | Background | Accent | Mood / best for |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function patchSchemaThemeLine(content) {
  const others = themeOrder()
    .filter((n) => n !== DEFAULT_THEME_NAME)
    .join(" | ");
  const line = new RegExp(
    `^(\\s*theme:\\s*${DEFAULT_THEME_NAME})(\\s*#.*)?$`,
    "m",
  );
  if (!line.test(content)) {
    throw new Error(
      `schema.md: no "theme: ${DEFAULT_THEME_NAME}" example line found`,
    );
  }
  return content.replace(
    line,
    `$1    # ${DEFAULT_THEME_NAME} (default) | ${others}`,
  );
}

const touched = [];
async function update(path, next) {
  const before = readFileSync(path, "utf8");
  const formatted = await prettierFormat(next, { filepath: path });
  if (before !== formatted) {
    writeFileSync(path, formatted);
    touched.push(path);
    console.log(`  updated ${path}`);
  } else {
    console.log(`  unchanged ${path}`);
  }
}

console.log("Generating command/theme doc sections…");

const readme = readFileSync(files.readme, "utf8");
await update(
  files.readme,
  replaceSection(
    replaceSection(readme, "minimal-api-table", readmeCommandTable()),
    "theme-table",
    readmeThemeTable(),
  ),
);

const install = readFileSync(files.install, "utf8");
await update(
  files.install,
  replaceSection(install, "theme-table", installThemeTable()),
);

await update(
  files.schema,
  patchSchemaThemeLine(readFileSync(files.schema, "utf8")),
);

console.log(`Done — ${touched.length} file(s) changed.`);
