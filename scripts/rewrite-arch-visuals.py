text = open(ARTICLE, encoding="utf-8").read()
lines = text.split("\n")
current = None
changed = []
for i, line in enumerate(lines):
    m = re.match(r"^  - id: (scene_\d+)\s*$", line)
    if m:
        current = m.group(1)
        continue
    if current and line.startswith("    visual: "):
        if current not in NEW:
            sys.exit(f"no rewrite for {current}")
        lines[i] = "    visual: " + NEW[current]
        changed.append(current)
        current = None

missing = sorted(set(NEW) - set(changed))
if missing:
    sys.exit(f"scenes never reached a visual line: {missing}")

open(ARTICLE, "w", encoding="utf-8").write("\n".join(lines))
print(f"rewrote {len(changed)} visual lines")
