for old, new in SHORTEN.items():
    if old not in text:
        sys.exit(f"narration not found: {old[:30]}")
    text = text.replace(old, new)

lines = text.split("\n")
current = None
changed = []
for i, line in enumerate(lines):
    m = re.match(r"^  - id: (scene_\d+)\s*$", line)
    if m:
        current = m.group(1)
        continue
    if current and line.startswith("    visual: "):
        if current not in NEW_VISUAL:
            sys.exit(f"no rewrite for {current}")
        lines[i] = "    visual: " + NEW_VISUAL[current]
        changed.append(current)
        current = None

missing = sorted(set(NEW_VISUAL) - set(changed))
if missing:
    sys.exit(f"scenes never reached a visual line: {missing}")

text = "\n".join(lines)

# theme: — `--style` does NOT stamp into the frontmatter; without it the
# theme silently reverts to the default on every re-derive.
