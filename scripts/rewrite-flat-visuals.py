# Explicit components to drop: an empty MapInsert sheet and a pyramid whose
# layer labels degrade to generic placeholders.
DROP_COMPONENT = {"scene_7", "scene_18"}

text = open(ARTICLE, encoding="utf-8").read()
lines = text.split("\n")
current = None
changed = []
dropped = []
for i, line in enumerate(lines):
    m = re.match(r"^  - id: (scene_\d+)\s*$", line)
    if m:
        current = m.group(1)
        continue
    if current and line.startswith("    visual: "):
        if current not in NEW_VISUAL:
            sys.exit(f"no rewrite for {current}")
        lines[i] = "    visual: " + NEW_VISUAL[current]
        changed.append(current)
        continue
    if current and line.startswith("    component: "):
        if current in DROP_COMPONENT:
            lines[i] = None  # removed below
            dropped.append(current)
        current = None

lines = [l for l in lines if l is not None]
text = "\n".join(lines)

missing = sorted(set(NEW_VISUAL) - set(changed))
if missing:
    sys.exit(f"scenes never reached a visual line: {missing}")

# theme: — `--style` does NOT stamp into the frontmatter; without it the theme
# silently reverts to the default on every re-derive.
if "\ntheme:" not in text:
    text = text.replace(
        "tts_provider: minimax\n---",
        "tts_provider: minimax\ntheme: paper-light\n---",
        1,
    )

# Opening beat: a beat of silence before the first line lands.
text = re.sub(
    r"(^  - id: scene_1\n    duration: \d+\n)",
    r"\1    lead_in_sec: 1.2\n",
    text,
    count=1,
    flags=re.M,
)

open(ARTICLE, "w", encoding="utf-8").write(text)
print(
    f"rewrote {len(changed)} visual lines, dropped components: {', '.join(dropped)}"
)
